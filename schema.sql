create table if not exists public.book_club_list (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    title text not null,
    author text,
    google_data jsonb,
    status text not null default 'Saved'
        check (status in (
            'Saved',
            'Priority',
            'Possible',
            'Later',
            'Deprioritize',
            'Read',
            'Proposed',
            'Scheduled',
            'Test'
        )),
    rating numeric(3, 1) check (rating >= 0 and rating <= 5),
    rating_source text,
    rating_count integer,
    tags text[] default '{}'::text[],
    target_date date,
    meeting_time text,
    user_notes text,
    host_name text,
    discussion_questions text,
    proposed_by_user_id uuid references auth.users(id) on delete set null,
    last_modified_by uuid references auth.users(id) on delete set null,
    last_modified_at timestamp with time zone
);

comment on table public.book_club_list is 'Shared single-club reading list and meeting planner.';
comment on column public.book_club_list.status is 'Shared workflow state. Test is a temporary sandbox status until multi-club support exists.';
comment on column public.book_club_list.rating is 'Stored club-facing rating from Goodreads, Google Books, Open Library, or manual override.';
comment on column public.book_club_list.rating_source is 'Source of the stored rating: goodreads, googlebooks, openlibrary, or manual.';
comment on column public.book_club_list.rating_count is 'Approximate number of ratings from the chosen source.';
comment on column public.book_club_list.tags is 'Club tags used for browsing and discussion.';
comment on column public.book_club_list.meeting_time is 'Meeting time stored as app-friendly string (for example 19:15 or 19:15:00).';
comment on column public.book_club_list.discussion_questions is 'Shared official discussion guide text for the club.';
comment on column public.book_club_list.proposed_by_user_id is 'Auth user who originally proposed the book.';
comment on column public.book_club_list.last_modified_by is 'Auth user who last changed shared metadata.';

