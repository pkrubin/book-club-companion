create table if not exists public.invite_codes (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    code text not null unique,
    valid_from timestamp with time zone,
    valid_until timestamp with time zone,
    max_uses integer,
    current_uses integer not null default 0
);

comment on table public.invite_codes is 'Current invite-only signup gate. This table is still client-driven and should eventually move behind a server-side RPC.';

-- Note: the current signup flow validates invite codes before authentication.
-- Because of that, the live app cannot yet use strict RLS on this table without
-- additional server-side work.

-- ---------------------------------------------------------------------------
-- Schedule change notifications
-- ---------------------------------------------------------------------------

create table if not exists public.schedule_changes (
    id bigint generated by default as identity primary key,
    book_id bigint references public.book_club_list(id) on delete cascade,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    book_title text not null,
    change_type text not null check (change_type in ('host', 'date', 'time')),
    old_value text,
    new_value text,
    changed_by_name text
);

create index if not exists idx_schedule_changes_created_at on public.schedule_changes (created_at desc);
create index if not exists idx_schedule_changes_book_id on public.schedule_changes (book_id);

alter table public.schedule_changes enable row level security;

drop policy if exists "Authenticated users can read schedule changes" on public.schedule_changes;
