-- Consolidated application schema for Book Club Companion.
-- This file is intended to reflect the current app shape in the repository.
-- It includes the core tables, current status values, and the current
-- single-club permission model.

begin;

-- ---------------------------------------------------------------------------
-- User profiles
-- ---------------------------------------------------------------------------

create table if not exists public.user_profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    display_name text not null,
    role text not null default 'member'
        check (role in ('admin', 'member')),
    last_seen_at timestamp with time zone
);

comment on table public.user_profiles is 'Lightweight profile and role record for each auth user.';
comment on column public.user_profiles.role is 'Single-club role model. Multi-club support will likely replace this with memberships.';

alter table public.user_profiles enable row level security;

drop policy if exists "Authenticated users can read profiles" on public.user_profiles;
create policy "Authenticated users can read profiles"
    on public.user_profiles
    for select
    to authenticated
    using (true);

drop policy if exists "Users can create their own profile" on public.user_profiles;
create policy "Users can create their own profile"
    on public.user_profiles
    for insert
    to authenticated
    with check (auth.uid() = id);

drop policy if exists "Users can update their own profile" on public.user_profiles;
create policy "Users can update their own profile"
    on public.user_profiles
    for update
    to authenticated
    using (auth.uid() = id)
    with check (auth.uid() = id);

-- ---------------------------------------------------------------------------
-- Shared helper for role-aware policies and triggers
-- ---------------------------------------------------------------------------

create or replace function public.is_book_club_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.user_profiles
        where id = auth.uid()
          and role = 'admin'
    );
$$;

revoke all on function public.is_book_club_admin() from public;
grant execute on function public.is_book_club_admin() to authenticated;

